-- ═══════════════════════════════════════════════════════════════════
-- REPLICA chat · make sure the Vault pepper exists
-- Run AFTER 038_pepper_vault.sql in the Supabase SQL Editor.
-- (idempotent — safe to re-run)
-- ═══════════════════════════════════════════════════════════════════
--
-- WHY
--   038 reads the password pepper from Vault and *fails closed*: if the
--   secret `ptr29_pepper_v2` is missing, register_account() raises
--   "ptr29_pepper_v2 is missing or too short" and every signup fails with
--   HTTP 400. The client only sees an RPC error, so the UI reports a
--   generic "server could not complete that request" and it looks like the
--   app cannot add users at all.
--
--   This migration creates the secret once, with a value generated inside
--   the database (it is never written to the repo or the SQL file). An
--   existing secret is NEVER overwritten: accounts may already be hashed
--   with it, and replacing it would lock those users out.
--
--   Fresh deployments can run 038 and then this file without doing the
--   manual `vault.create_secret(...)` step first.

create extension if not exists supabase_vault with schema vault;

do $$
declare
  existing text;
begin
  select decrypted_secret into existing
    from vault.decrypted_secrets
   where name = 'ptr29_pepper_v2'
   order by created_at desc
   limit 1;

  if existing is null then
    -- Two UUIDs = 256 bits of randomness, stored as 64 hex characters.
    perform vault.create_secret(
      replace(gen_random_uuid()::text, '-', '') ||
      replace(gen_random_uuid()::text, '-', ''),
      'ptr29_pepper_v2',
      'ptr29 account password pepper, v2 (generated by 039_ensure_pepper_secret.sql)'
    );
    raise notice 'Created Vault secret ptr29_pepper_v2';
  elsif length(existing) < 32 then
    raise exception
      'ptr29_pepper_v2 exists but is shorter than 32 characters. Refusing to overwrite it because existing accounts may be hashed with it. Create a new version with vault.create_secret() and bump ptr29_current_pepper_version().';
  else
    raise notice 'Vault secret ptr29_pepper_v2 already present';
  end if;
end $$;

-- Verification: this is the exact call register_account()/login_account()
-- make, so it raises here if registration would still fail.
do $$
begin
  perform public.ptr29_pepper(public.ptr29_current_pepper_version());
  raise notice 'Pepper check OK — registration will accept new accounts';
end $$;
